-- Техника выполнения: одна строка на упражнение (связь 1:1, поэтому exercise_id — и первичный ключ).
-- Шаги и ошибки — массивы text[]: их всегда читают целиком и по порядку, отдельная таблица не нужна.
CREATE TABLE exercise_technique (
    exercise_id UUID   PRIMARY KEY,
    setup       TEXT   NOT NULL,      -- исходное положение
    steps       TEXT[] NOT NULL,      -- как выполнять, по шагам
    mistakes    TEXT[] NOT NULL,      -- частые ошибки

    CONSTRAINT fk_exercise_technique_exercise FOREIGN KEY (exercise_id) REFERENCES exercises (id) ON DELETE CASCADE
);
--rollback DROP TABLE exercise_technique;

