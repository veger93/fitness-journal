package com.vegas.analytics.dto;

/**
 * Виды личных рекордов. На экране называются по-человечески:
 * WEIGHT — "Вес": поднят самый большой вес за всё время, при любом числе повторов;
 * E1RM   — "Сила": вырос расчётный максимум на 1 повтор (например, тот же вес, но больше повторов).
 */
public enum RecordType {
    WEIGHT,
    E1RM
}
