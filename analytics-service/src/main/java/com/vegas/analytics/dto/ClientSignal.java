package com.vegas.analytics.dto;

/**
 * Главный сигнал по клиенту для тренера (метка в списке "Чей дневник открыть", docs/trainer.md, шаг 5).
 * Порядок = приоритет: показываем один, самый важный. "Идёт тренировка" — ещё важнее, но это знает workout-service,
 * фронт ставит его сам поверх этого сигнала.
 */
public enum ClientSignal {
    OVERLOAD, // высокий риск перегрузки хотя бы в одном упражнении
    PLATEAU,  // плато: давно нет нового максимума
    AWAY,     // больше недели без тренировок
    RECORD,   // рекорд за последнюю неделю
    NONE      // всё спокойно (или тренировок ещё нет)
}
